"""
JWT verification for tokens generated by Spring Boot.
"""

import base64

import jwt

from fastapi import Header, HTTPException, status

from config import JWT_SECRET_KEY


# =========================================================
# JWT SECRET
# =========================================================

_secret_bytes = base64.b64decode(
    JWT_SECRET_KEY
)


# =========================================================
# VERIFY TOKEN
# =========================================================

def verify_token(
    authorization: str = Header(None)
):

    # -----------------------------------------------------
    # Authorization header
    # -----------------------------------------------------

    if (
        not authorization
        or not authorization.startswith("Bearer ")
    ):

        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail=(
                "Token manquant ou mal forme "
                "(attendu: Authorization: Bearer <token>)"
            )
        )


    # -----------------------------------------------------
    # Extract JWT
    # -----------------------------------------------------

    token = (
        authorization
        .removeprefix("Bearer ")
        .strip()
    )


    # -----------------------------------------------------
    # Decode JWT
    # -----------------------------------------------------

    try:

        payload = jwt.decode(
            token,
            _secret_bytes,
            algorithms=["HS256"]
        )


    except jwt.ExpiredSignatureError:

        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Token expire"
        )


    except jwt.InvalidTokenError:

        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Token invalide"
        )


    return payload